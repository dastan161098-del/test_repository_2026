# Example 1
square = lambda x: x * x
print(square(5))

# Example 2
add = lambda a, b: a + b
print(add(3, 7))

# Example 3: проверка четности
is_even = lambda x: x % 2 == 0
print(is_even(4))

# Example 4: максимум
max_two = lambda a, b: a if a > b else b
print(max_two(5, 9))

# Example 5: длина строки
length = lambda s: len(s)
print(length("python"))